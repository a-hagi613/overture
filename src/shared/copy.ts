const COUNT_WORDS = [
  "zero",
  "one",
  "two",
  "three",
  "four",
  "five",
  "six",
  "seven",
  "eight",
  "nine",
  "ten",
  "eleven",
  "twelve",
  "thirteen",
  "fourteen",
  "fifteen",
  "sixteen",
  "seventeen",
  "eighteen",
  "nineteen",
] as const;

const TENS_WORDS = [
  "",
  "",
  "twenty",
  "thirty",
  "forty",
  "fifty",
  "sixty",
  "seventy",
  "eighty",
  "ninety",
] as const;

function countWord(count: number) {
  if (count < 20) {
    return COUNT_WORDS[count] ?? String(count);
  }

  if (count < 100) {
    const tens = TENS_WORDS[Math.floor(count / 10)] ?? "";
    const ones = count % 10;

    return ones === 0 ? tens : `${tens}-${COUNT_WORDS[ones] ?? ""}`;
  }

  return String(count);
}

function capitalize(word: string) {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

