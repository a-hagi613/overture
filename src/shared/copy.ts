const TENS_WORDS = [
  "",
  "",
  "twenty",
  "thirty",
  "forty",
  "fifty",
  "sixty",
  "seventy",
  "eighty",
  "ninety",
] as const;

function countWord(count: number) {
  if (count < 20) {
    return COUNT_WORDS[count] ?? String(count);
  }

  if (count < 100) {
    const tens = TENS_WORDS[Math.floor(count / 10)] ?? "";
    const ones = count % 10;

    return ones === 0 ? tens : `${tens}-${COUNT_WORDS[ones] ?? ""}`;
  }

  return String(count);
}

function capitalize(word: string) {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

function plural(count: number, one: string, many: string) {
  return count === 1 ? one : many;
}

function possessive(name: string) {
  const trimmed = name.trim();

  return trimmed.endsWith("s") || trimmed.endsWith("S") ? `${trimmed}’` : `${trimmed}’s`;
}

function ordinal(count: number) {
  const remainder = count % 100;

  if (remainder >= 11 && remainder <= 13) {
    return `${String(count)}th`;
  }

  if (count % 10 === 1) {
    return `${String(count)}st`;
  }

  if (count % 10 === 2) {
    return `${String(count)}nd`;
  }

  if (count % 10 === 3) {
    return `${String(count)}rd`;
  }

  return `${String(count)}th`;
}

